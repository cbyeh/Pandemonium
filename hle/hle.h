/** Display list / scratch buffers of the current task (vrdp.c). */
extern uint64_t *__gbi_ptr, *__gbi_end;
extern uint8_t *__gbi_scratch, *__gbi_scratch_end;
/** Submits the current task and starts a new one (vrdp.c). */
void gbi_split(void);

/** Raw GBI emission (room must have been reserved with gbi_reserve). */
static inline void gbi(uint32_t w0, uint32_t w1)
{
    *__gbi_ptr++ = ((uint64_t)w0 << 32) | w1;
}
/** Make sure there is room for `ncmds` commands and `nbytes` of scratch in this task. */
static inline void gbi_reserve(int ncmds, int nbytes)
{
    // keep room for the closing commands (flush, FULLSYNC, ENDDL)
    if (__builtin_expect(__gbi_ptr + ncmds + 4 > __gbi_end || __gbi_scratch + nbytes > __gbi_scratch_end, 0))
        gbi_split();
}
/** Per-task scratch memory for vertices/matrices referenced by the display list. */
static inline void* gbi_alloc(int bytes)
{
    void *p = __gbi_scratch;
    __gbi_scratch += (bytes + 15) & ~15;
    return p;
}

/** 4x4 float matrix, column-major (m[col][row]), same convention as T3DMat4. */
typedef float hle_mat4_t[4][4];

/** RSP-side geometry state, as seen by the F3DEX2 display list. */
typedef struct {
    const hle_mat4_t *proj;
    uint32_t proj_ver;
    int16_t vp[8];          ///< Vp (vscale[4], vtrans[4]), 1/4 pixel units
    uint32_t vp_ver;
    uint32_t geom;          ///< F3DEX2 geometry mode
    uint32_t tex;           ///< G_TEXTURE w0 low bits (0 = off)
    uint32_t fog;           ///< G_MW_FOG word with G_FOG set (0 = off)
} gsp_state_t;

extern gsp_state_t gsp_3d;
/**
 * Incremented whenever the graphics plugin's matrix state is lost (new task)
 * or clobbered (2D draws), so the modelview stack must be rebuilt.
 */
extern uint32_t gsp_epoch;
/** Graphics tasks submitted so far (the plugin is done with everything before). */
extern uint32_t gsp_tasks;
/** Bump when the projection changes. */
static inline void gsp_3d_proj(const hle_mat4_t *m) { gsp_3d.proj = m; gsp_3d.proj_ver++; }
/** Emits whatever 3D state changed since the last sync (call before G_VTX/G_TRI). */
void gsp_sync_3d(void);
/** Switches to a pixel-space ortho camera for 2D triangles. */
void gsp_sync_2d(uint32_t geom, uint32_t tex);
/** Emits a float matrix as G_MTX (LOAD/NOPUSH) with the given G_MTX_MODELVIEW/PROJECTION. */
void gbi_mtx(const hle_mat4_t *m, uint32_t which);

/** Processes consecutive Tiny3D TRI_DRAW commands starting at `a`; returns the bytes consumed. */
int hle_t3d_tri_run(const uint32_t *a, uint32_t cmd_byte);
/** Pending Tiny3D triangles must reach the display list before anything else (ovl_t3d.c). */
void hle_t3d_flush(void);

/** Debug log (only to ISViewer/emulator console). */
void hle_logf(const char *fmt, ...);
/** Logs a message only the first time `key` is seen. */
void hle_warn_once(const char *key, const char *fmt, ...);


// ---- Block replay (replay.c) ----

/** State snapshot cursor: copies a variable out (save) or back in (load). */
typedef struct { uint8_t *p; bool load; } hle_st_t;
static inline void hle_st(hle_st_t *s, void *var, int n)
{
    if (s->load) memcpy(var, s->p, n); else memcpy(s->p, var, n);
    s->p += n;
}
#define HLE_ST(s, v) hle_st((s), &(v), sizeof(v))

