/**
 * HLE backend: runs libdragon's RSP command queue on the CPU and turns the
 * resulting RDP work into F3DEX2 display lists, so the game renders on
 * high-level-emulation N64 emulators (e.g. Mupen64Plus + GLideN64 in Delta)
 * that cannot run libdragon/Tiny3D microcode.
 *
 * Built only with `make HLE=1`. The resulting ROM does NOT run on real hardware.
 */
#ifndef HLE_H
#define HLE_H

#include <stdint.h>
#include <stdbool.h>

// ---- Virtual RSP (rspq_hle.c) ----

/**
 * Virtual DMEM. The common rspq area (DMEM 0..sizeof(rsp_queue_t)) is the
 * rsp_queue_t at `__vrsp_dmem`; each overlay keeps a private 4 KB image for
 * the rest, so switching overlays costs nothing. VDMEMxx access the image of
 * the overlay being executed, with real DMEM offsets.
 */
extern uint8_t __vrsp_dmem[4096];
extern uint8_t *__vrsp_img;
#define VDMEM8(a)  (*(uint8_t*) (__vrsp_img + ((a) & 0xFFF)))
#define VDMEM16(a) (*(uint16_t*)(__vrsp_img + ((a) & 0xFFE)))
#define VDMEM32(a) (*(uint32_t*)(__vrsp_img + ((a) & 0xFFC)))
#define VDMEM_PTR(a) ((void*)(__vrsp_img + ((a) & 0xFFF)))

/** RDRAM physical address -> uncached CPU pointer. */
static inline void* hle_rdram(uint32_t phys) {
    return (void*)(0xA0000000u | (phys & 0x00FFFFFFu));
}

/**
 * Overlay command handler. `cmd` is the command index inside the overlay,
 * `a` the command words (a[0] includes the command byte), `n` the word count.
 */
typedef void (*vrsp_handler_t)(uint32_t cmd, const uint32_t *a, int n);

/** RSPQ builtins used by overlays that emit RDP commands (RDPQ_Send & co). */
void vrsp_rdp_set_buffer(uint32_t a0, uint32_t a1, uint32_t a2);
void vrsp_rdp_append_buffer(uint32_t a0);
/** Emulates RDPQ_Send: forwards `nbytes` of RDP commands generated by the RSP. */
void vrsp_rdpq_send(const uint32_t *words, int nbytes);

// ---- Overlays ----
void ovl_rdpq(uint32_t cmd, const uint32_t *a, int n);
void ovl_t3d(uint32_t cmd, const uint32_t *a, int n);
void ovl_tpx(uint32_t cmd, const uint32_t *a, int n);
void ovl_mixer(uint32_t cmd, const uint32_t *a, int n);

/** DMEM offset of the current overlay's saved state. */
extern uint32_t __vrsp_state_start;
/** Z-buffer clear (vrdp.c) */
void vrdp_clear_z(uint32_t zaddr, uint32_t size, uint16_t value);

/** Tiny3D state shared with tinypx (ovl_t3d.c). */
void hle_t3d_matrices(const float (**proj)[4], const float (**mv)[4]);
/** out = l * r (column-major; out may alias l or r). */
void hle_mat_mul(float out[4][4], const float l[4][4], const float r[4][4]);
/** T3DMat4FP (s16.16, int/frac halves per column) to float. */
void hle_mat_from_fp(float out[4][4], const void *fp);

// ---- Virtual RDP -> F3DEX2 (vrdp.c) ----
void vrdp_init(void);
/** DP_START write. */
void vrdp_set_start(uint32_t phys);
/** DP_END write: translates RDRAM commands up to `phys`. */
void vrdp_set_end(uint32_t phys);
/** Moves the DP cursor to where an RSP handler is about to "write" (see vrsp_rdpq_send). */
void vrdp_sync_cursor(uint32_t phys);
/** Translates commands produced directly by an RSP handler (advances the cursor). */
void vrdp_direct(const uint64_t *cmds, int nbytes);

/** Display list / scratch buffers of the current task (vrdp.c). */
extern uint64_t *__gbi_ptr, *__gbi_end;
extern uint8_t *__gbi_scratch, *__gbi_scratch_end;
/** Submits the current task and starts a new one (vrdp.c). */
void gbi_split(void);

/** Raw GBI emission (room must have been reserved with gbi_reserve). */
static inline void gbi(uint32_t w0, uint32_t w1)
{
    *__gbi_ptr++ = ((uint64_t)w0 << 32) | w1;
}
/** Make sure there is room for `ncmds` commands and `nbytes` of scratch in this task. */
static inline void gbi_reserve(int ncmds, int nbytes)
{
    // keep room for the closing commands (flush, FULLSYNC, ENDDL)
    if (__builtin_expect(__gbi_ptr + ncmds + 4 > __gbi_end || __gbi_scratch + nbytes > __gbi_scratch_end, 0))
        gbi_split();
}
/** Per-task scratch memory for vertices/matrices referenced by the display list. */
static inline void* gbi_alloc(int bytes)
{
    void *p = __gbi_scratch;
    __gbi_scratch += (bytes + 15) & ~15;
    return p;
}

/** 4x4 float matrix, column-major (m[col][row]), same convention as T3DMat4. */
typedef float hle_mat4_t[4][4];

/** RSP-side geometry state, as seen by the F3DEX2 display list. */
typedef struct {
    const hle_mat4_t *proj;
    uint32_t proj_ver;
    int16_t vp[8];          ///< Vp (vscale[4], vtrans[4]), 1/4 pixel units
    uint32_t vp_ver;
    uint32_t geom;          ///< F3DEX2 geometry mode
    uint32_t tex;           ///< G_TEXTURE w0 low bits (0 = off)
} gsp_state_t;

extern gsp_state_t gsp_3d;
/**
 * Incremented whenever the graphics plugin's matrix state is lost (new task)
 * or clobbered (2D draws), so the modelview stack must be rebuilt.
 */
extern uint32_t gsp_epoch;
/** Bump when the projection changes. */
static inline void gsp_3d_proj(const hle_mat4_t *m) { gsp_3d.proj = m; gsp_3d.proj_ver++; }
/** Emits whatever 3D state changed since the last sync (call before G_VTX/G_TRI). */
void gsp_sync_3d(void);
/** Switches to a pixel-space ortho camera for 2D triangles. */
void gsp_sync_2d(uint32_t geom, uint32_t tex);
/** Emits a float matrix as G_MTX (LOAD/NOPUSH) with the given G_MTX_MODELVIEW/PROJECTION. */
void gbi_mtx(const hle_mat4_t *m, uint32_t which);

/** Processes consecutive Tiny3D TRI_DRAW commands starting at `a`; returns the bytes consumed. */
int hle_t3d_tri_run(const uint32_t *a, uint32_t cmd_byte);
/** Pending Tiny3D triangles must reach the display list before anything else (ovl_t3d.c). */
void hle_t3d_flush(void);

/** Debug log (only to ISViewer/emulator console). */
void hle_logf(const char *fmt, ...);
/** Logs a message only the first time `key` is seen. */
void hle_warn_once(const char *key, const char *fmt, ...);

#endif
