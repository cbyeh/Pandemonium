def parse(art):
    lines = art.strip('\n').split('\n')
    assert len(lines) == 16 and all(len(l) == 16 for l in lines), [(i, len(l), l) for i, l in enumerate(lines) if len(l) != 16] or len(lines)
    return [[LEVEL[c] * 17 for c in l] for l in lines]

def all_icons():
    out = []
    for name, f, tier, desc, art in BOONS:
        try: out.append((name, f, None, tier, desc, parse(art)))
        except AssertionError as e: raise SystemExit('%s: %s' % (name, e))
    for name, fa, fb, desc, art in DUOS:
        try: out.append((name, fa, fb, 2, desc, parse(art)))
        except AssertionError as e: raise SystemExit('%s: %s' % (name, e))
    return out
